using System;
using System.Collections.Generic;
using System.IO;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Winddy.Services;

public enum SearchMode { Exact, Fuzzy, Regexp, Mixed }
public enum SortBy { LastCopiedAt, FirstCopiedAt, NumberOfCopies }
public enum PinsPosition { Top, Bottom }
public enum PopupPosition { Cursor, TrayIcon, WindowCenter, ScreenCenter, LastPosition }
public enum HighlightMatch { Bold, Italic, Underline, Color }
public enum SearchVisibility { Always, DuringSearch }

public sealed class AppSettings
{
    // Formats that are always ignored: Windows' equivalent of the
    // org.nspasteboard Transient/Concealed/AutoGenerated types.
    public static readonly string[] AlwaysIgnoredFormats =
    {
        "ExcludeClipboardContentFromMonitorProcessing",
    };

    public static readonly string[] DefaultIgnoredFormats =
    {
        "Clipboard Viewer Ignore",
        "KeePassXC-Clipboard",
        "Bitwarden Clipboard",
    };

    /// <summary>Data folder; WINDDY_DATA_DIR overrides it (used by UI snapshot runs).</summary>
    public static string Directory { get; } =
        Environment.GetEnvironmentVariable("WINDDY_DATA_DIR") is { Length: > 0 } custom
            ? custom
            : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "Winddy");

    private static string FilePath => Path.Combine(Directory, "settings.json");

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public static AppSettings Current { get; private set; } = new();

    public static event Action? Changed;

    // General
    public string OpenHotkey { get; set; } = "Ctrl+Shift+C";
    public string PinHotkey { get; set; } = "Alt+P";
    public string DeleteHotkey { get; set; } = "Alt+Back";
    public string PreviewHotkey { get; set; } = "Ctrl+Space";
    public SearchMode SearchMode { get; set; } = SearchMode.Exact;
    public bool PasteByDefault { get; set; }
    public bool RemoveFormattingByDefault { get; set; }
    public bool CheckForUpdates { get; set; } = true;
    public DateTime? LastUpdateCheck { get; set; }
    public string? SkippedVersion { get; set; }
    public bool ShowNotifications { get; set; }
    public bool PlaySounds { get; set; }

    // Storage
    public bool SaveFiles { get; set; } = true;
    public bool SaveImages { get; set; } = true;
    public bool SaveText { get; set; } = true;
    public int HistorySize { get; set; } = 200;
    public SortBy SortBy { get; set; } = SortBy.LastCopiedAt;

    // Appearance
    public PopupPosition PopupPosition { get; set; } = PopupPosition.Cursor;
    public PinsPosition PinTo { get; set; } = PinsPosition.Top;
    public int ImageMaxHeight { get; set; } = 40;
    public bool OpenPreviewAutomatically { get; set; } = true;
    public int PreviewDelay { get; set; } = 1500;
    public HighlightMatch HighlightMatch { get; set; } = HighlightMatch.Bold;
    public bool ShowSpecialSymbols { get; set; } = true;
    public bool ShowInTray { get; set; } = true;
    public bool ShowRecentCopyInTray { get; set; }
    public bool ShowSearch { get; set; } = true;
    public SearchVisibility SearchVisibility { get; set; } = SearchVisibility.Always;
    public bool ShowTitle { get; set; } = true;
    public bool ShowApplicationIcons { get; set; }
    public bool ShowHexColorSwatch { get; set; } = true;
    public bool ShowFooter { get; set; } = true;
    public double WindowWidth { get; set; } = 450;
    public double WindowHeight { get; set; } = 800;
    public int? LastPositionX { get; set; }
    public int? LastPositionY { get; set; }

    // Ignore
    public List<string> IgnoredApps { get; set; } = new();
    public bool IgnoreAllAppsExceptListed { get; set; }
    public List<string> IgnoredFormats { get; set; } = new(DefaultIgnoredFormats);
    public List<string> IgnoreRegexp { get; set; } = new();

    // Advanced
    public bool IgnoreEvents { get; set; }
    public bool IgnoreOnlyNextEvent { get; set; }
    public bool ClearOnQuit { get; set; }
    public bool ClearSystemClipboard { get; set; }
    public int ClipboardCheckDelay { get; set; } = 50;

    // Internal
    public bool SuppressClearAlert { get; set; }
    public List<string> PinOrder { get; set; } = new();
    public string? Language { get; set; }

    public static void Load()
    {
        try
        {
            if (File.Exists(FilePath))
                Current = JsonSerializer.Deserialize<AppSettings>(File.ReadAllText(FilePath), JsonOptions) ?? new AppSettings();
        }
        catch
        {
            Current = new AppSettings();
        }
    }

    public static void Save()
    {
        try
        {
            System.IO.Directory.CreateDirectory(Directory);
            var tmp = FilePath + ".tmp";
            File.WriteAllText(tmp, JsonSerializer.Serialize(Current, JsonOptions));
            File.Move(tmp, FilePath, true);
        }
        catch
        {
            // Settings are best effort; nothing sensible to do on failure.
        }
        Changed?.Invoke();
    }

    public static void Update(Action<AppSettings> change)
    {
        change(Current);
        Save();
    }
}
